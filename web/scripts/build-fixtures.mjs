// npm run fixtures
// Builds src/fixtures/bundle.json (what fixture mode renders) from lane B's contract fixtures.
// Source: docs/contracts/fixtures/ when present on this branch, else the copies in src/fixtures/laneb/.
// Fills only display fields lane B leaves out of expected exceptions (state, evidence, timestamps) with
// neutral defaults; never fills money, minutes, rates or policy values.
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const docs = join(here, '../../docs/contracts/fixtures')
const local = join(here, '../src/fixtures/laneb')
mkdirSync(local, { recursive: true })
if (existsSync(docs)) for (const f of readdirSync(docs).filter((n) => n.endsWith('.json'))) copyFileSync(join(docs, f), join(local, f))
const read = (f) => JSON.parse(readFileSync(join(local, f), 'utf8'))

const snap = read('cycle_synthetic_v1.json')
const expected = read('expected_exceptions_v1.json')
const matrix = read('readiness_matrix_v1.json')
const cycle = snap.cycle
const at = snap.captured_at

const KIND_BY_PREFIX = [['ci_quote_', 'quote_commission'], ['ci_marketing_', 'marketing'], ['ci_tip_', 'tip'], ['ci_manager', 'manager_pool']]
const kindOf = (id) => (KIND_BY_PREFIX.find(([p]) => id.startsWith(p)) ?? [null, null])[1]
const jobOf = (id) => (id.match(/job_\d+/) ?? [null])[0]
const fixReadiness = (r) => ({ ...r, last_computed_at: r.last_computed_at ?? at })

function readiness(side) {
  const items = []
  for (const [wid, r] of Object.entries(side.workers ?? {})) {
    items.push({
      id: `ci_wages_${wid}`, cycle_id: cycle.id, kind: 'wages', worker_id: wid, job_id: null,
      policy_version: cycle.policy_version, inputs: {},
      computed: { gross_cents: (side.stage1_gross_new_cents ?? {})[wid] ?? null },
      readiness: fixReadiness(r), obligation_ids: [], provenance: 'synthetic',
    })
  }
  for (const [id, r] of Object.entries(side.items ?? {})) {
    const kind = kindOf(id)
    if (!kind) { console.warn(`skip unknown item kind: ${id}`); continue }
    items.push({
      id, cycle_id: cycle.id, kind, worker_id: null, job_id: jobOf(id), policy_version: cycle.policy_version,
      inputs: {}, computed: null, readiness: fixReadiness(r), obligation_ids: [], provenance: 'synthetic',
    })
  }
  return { stage1: fixReadiness(side.stage1), items }
}

const exceptions = expected.exceptions.map((e) => ({
  cycle_id: cycle.id, observed: e.note && e.note.length > 12 ? e.note : e.title, expected: '—', evidence: [], dollars_affected_cents: null,
  state: 'detected', next_action: `ask ${e.intended_respondent_role.replace('_', ' ')}`, owner_agent: 'audit',
  message_ids: [], resolution_id: null, provenance: 'seeded_issue', created_at: at, updated_at: at,
  ...e,
  entity_refs: { worker_id: null, time_entry_ids: [], job_ids: [], cost_ids: [], ...e.entity_refs },
}))
for (const e of exceptions) delete e.note

const bundle = {
  _note: 'GENERATED by scripts/build-fixtures.mjs from lane B fixtures. All synthetic. Do not edit by hand.',
  health: { ok: true, contract_version: '1', integrations: { photon: 'unverified', band: 'unverified', cognee: 'unverified', browser_use: 'unverified' } },
  cycle,
  workers: snap.workers,
  readiness: readiness(matrix.before),
  readiness_after_t02: readiness(matrix.after_t02_correction),
  exceptions,
  replies: read('replies_v1.json').replies,
  events: [
    { id: 'evt_fx_001', at, cycle_id: cycle.id, actor: 'system', type: 'cycle.created', summary: 'Loaded synthetic fixture cycle', refs: {}, usage: null, duration_ms: null },
    { id: 'evt_fx_002', at, cycle_id: cycle.id, actor: 'audit', type: 'audit.completed', summary: `${exceptions.length} exceptions detected (fixture)`, refs: {}, usage: null, duration_ms: null },
  ],
}
writeFileSync(join(here, '../src/fixtures/bundle.json'), JSON.stringify(bundle, null, 1) + '\n')
console.log(`bundle.json: ${exceptions.length} exceptions, ${bundle.readiness.items.length} items, ${snap.workers.length} workers`)
